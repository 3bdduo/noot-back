const catalogues: Record<Locale, Catalogue> = { ar, en };

export function translate(locale: Locale, code: string, params: Record<string, unknown> = {}): string {
  const template = catalogues[locale]?.[code] ?? catalogues.en[code] ?? catalogues.en.INTERNAL_ERROR;
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const v = params[key];
    return v === undefined || v === null ? '' : String(v);
  });
}
